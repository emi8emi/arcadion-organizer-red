-- Party ratings and feedback. Players now rate the party as a whole (like / dislike) and can send feedback
-- that names players, with a category. The bot infers who likes playing with whom from the ratings and
-- turns tagged feedback into weighted dislikes; the old per-player `votes` stay readable until they expire.
-- Never shown to players; organizers see aggregates and anonymised notes only (/feedback).
-- Ratings are append-only: the latest row per (voter, party) is the current rating.
CREATE TABLE party_ratings (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       INTEGER NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
    slot_id      INTEGER NOT NULL REFERENCES slots(id) ON DELETE CASCADE,
    party_id     INTEGER NOT NULL REFERENCES parties(id) ON DELETE CASCADE,
    voter_id     TEXT NOT NULL,
    vote         TEXT NOT NULL CHECK (vote IN ('like', 'dislike')),
    created_utc  TEXT NOT NULL
);
CREATE INDEX party_ratings_voter ON party_ratings (voter_id, party_id, created_utc);

-- One row per (reporter, party, player named, category). Sending feedback again for the same party replaces
-- the reporter's earlier rows. target_id is NULL for feedback that names nobody.
CREATE TABLE party_feedback (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id       INTEGER NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
    slot_id      INTEGER NOT NULL REFERENCES slots(id) ON DELETE CASCADE,
    party_id     INTEGER NOT NULL REFERENCES parties(id) ON DELETE CASCADE,
    reporter_id  TEXT NOT NULL,
    target_id    TEXT,
    category     TEXT NOT NULL CHECK (category IN ('toxic', 'communication', 'late_no_show', 'performance', 'other')),
    note         TEXT NOT NULL DEFAULT '',
    created_utc  TEXT NOT NULL
);
CREATE INDEX party_feedback_target ON party_feedback (target_id, created_utc);
CREATE INDEX party_feedback_party ON party_feedback (party_id, reporter_id);
