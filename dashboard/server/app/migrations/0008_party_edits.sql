-- Party composition edits: seats filled by players from Party Finder, and the new kinds of change.
--
-- party_pf: a seat in an approved party taken by someone who did not sign up through the bot (Party Finder). They have
-- no Discord account here, so they are not party_members (no pings, confirmations or ratings); the row only records
-- that the seat is filled, with which role and an optional label, so the fill can be tracked afterwards.
-- party_changes.kind: 'move' (to another party of the same slot), 'remove' (leaves the party short), 'add' (joins a
-- short party), 'pf_add' and 'pf_remove'. Additive; existing rows keep working.
CREATE TABLE party_pf (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id   INTEGER NOT NULL REFERENCES parties(id) ON DELETE CASCADE,
    role       TEXT NOT NULL CHECK (role IN ('main_tank', 'off_tank', 'regen', 'shield', 'melee', 'ranged', 'caster')),
    name       TEXT,
    added_utc  TEXT NOT NULL,
    added_by   TEXT NOT NULL
);
CREATE INDEX idx_party_pf_party ON party_pf(party_id);

ALTER TABLE party_changes DROP CONSTRAINT party_changes_kind_check;
ALTER TABLE party_changes ADD CONSTRAINT party_changes_kind_check CHECK (
    kind IN ('swap', 'role', 'ended', 'end_override', 'end_undo', 'move', 'remove', 'add', 'pf_add', 'pf_remove'));
